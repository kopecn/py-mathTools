"""Trajectory container + sampler: the computed motion for all DOFs.

Faithful port of ``SWIFT_MATH/OTG/Trajectory.swift``. See
``.claude/specs/otg.md`` §Public API (Trajectory) and
``.claude/action-plan/35-otg-trajectory-and-output.md``.

``atTime``'s several Swift overloads (``inout`` arrays, single-DOF scalars,
``newSection``/``newJerk`` variants) collapse into one Python entry point:
:meth:`Trajectory.at_time` returns ``(positions, velocities,
accelerations)`` directly (matching the Swift convenience overload used by
external callers), backed by the private :meth:`Trajectory._state_to_integrate_from`
(mirrors ``stateToIntegrateFrom`` exactly, including the section index --
available for the driver, chunk 41, to reuse). ``time`` is clamped to
``[0, duration]`` before sampling, per ``otg.md`` §Public API ("clamped to
``[0, duration]`` ends per Swift").

``Profile.getPositionExtrema``/``getFirstStateAtPosition`` (Swift) were
explicitly deferred by chunk 33 to "a later chunk (35, trajectory
sampling)" (see ``33-otg-profile.md``'s Resolution notes) because both
depend on things chunk 33 didn't carry: aggregating across the brake
sub-profile (a ``Trajectory``-level concern) and the cubic root solver.
Both are ported here as module-private functions operating on a
``Profile`` instance's already-public fields plus
``Profile.check_step_for_position_extremum`` (already a public
``staticmethod``) and ``math_tools.functional.roots.solve_cubic`` --
deliberately NOT new methods on ``Profile`` itself, since this chunk's own
file list does not include ``profile.py`` and the stay-in-scope default
posture calls for the minimal change that satisfies the ask.
"""

from __future__ import annotations

import math
import sys

from math_tools.functional.roots import integrate_jerk, solve_cubic
from math_tools.otg.bound import Bound
from math_tools.otg.profile import Profile

__all__ = ["Trajectory"]

#: Swift ``Double.ulpOfOne`` -- matches ``profile.py``/``brake.py``/
#: ``block.py``'s identical convention for their own private near-equality
#: tolerance (not ``functional.roots.EPS16``, a different, unrelated
#: constant used only by the polynomial-root kernel).
_ULP = sys.float_info.epsilon


class Trajectory:
    """The trajectory generated by the Ruckig algorithm: per-DOF ``Profile``
    sections plus the synchronized sampling logic.

    ``profiles`` is a list of sections; each section is a list of one
    ``Profile`` per DOF. A trajectory with no intermediate waypoints has
    exactly one section (``max_number_of_waypoints=0``, the default) --
    this collapses Swift's two constructor overloads (``init(dofs:)`` and
    ``init(dofs:maxNumberOfWaypoints:)``) into one, since
    ``maxNumberOfWaypoints=0`` already produces the same single-section
    shape as the no-waypoints overload.
    """

    def __init__(self, dofs: int, max_number_of_waypoints: int = 0) -> None:
        self.degrees_of_freedom = dofs

        num_sections = max_number_of_waypoints + 1
        self.profiles: list[list[Profile]] = [
            [Profile() for _ in range(dofs)] for _ in range(num_sections)
        ]
        self.cumulative_times: list[float] = [0.0] * num_sections

        self.duration: float = 0.0
        self.independent_min_durations: list[float] = [0.0] * dofs

    # MARK: - Sampling

    def _state_to_integrate_from(
        self, time: float
    ) -> tuple[int, list[tuple[float, float, float, float, float]]]:
        """``stateToIntegrateFrom`` -- for each DOF, the ``(t, p, v, a, j)``
        arguments to feed :func:`~math_tools.functional.roots.integrate_jerk`,
        plus the section index reached at ``time``.

        ``time`` is assumed already clamped to ``[0, duration]`` by the
        caller (:meth:`at_time`).
        """
        dofs = self.degrees_of_freedom

        if time >= self.duration:
            # Keep constant acceleration beyond the trajectory's end.
            new_section = len(self.profiles)
            last_section = self.profiles[-1]
            args: list[tuple[float, float, float, float, float]] = []
            for dof in range(dofs):
                profile = last_section[dof]
                t_pre = (
                    self.cumulative_times[-2]
                    if len(self.profiles) > 1
                    else profile.brake.duration
                )
                t_diff = time - (t_pre + profile.t_sum[-1])
                args.append((t_diff, profile.p[-1], profile.v[-1], profile.a[-1], 0.0))
            return new_section, args

        # Find the correct section (first cumulative time strictly after `time`).
        new_section = len(self.cumulative_times)
        for section_i, cumulative in enumerate(self.cumulative_times):
            if cumulative > time:
                new_section = section_i
                break

        t_diff = time
        if new_section > 0:
            t_diff -= self.cumulative_times[new_section - 1]

        args = []
        for dof in range(dofs):
            profile = self.profiles[new_section][dof]
            t_diff_dof = t_diff

            # Brake pre-trajectory (only ever present in the first section).
            if new_section == 0 and profile.brake.duration > 0:
                if t_diff_dof < profile.brake.duration:
                    index = 0 if t_diff_dof < profile.brake.t[0] else 1
                    if index > 0:
                        t_diff_dof -= profile.brake.t[index - 1]
                    args.append(
                        (
                            t_diff_dof,
                            profile.brake.p[index],
                            profile.brake.v[index],
                            profile.brake.a[index],
                            profile.brake.j[index],
                        )
                    )
                    continue
                t_diff_dof -= profile.brake.duration

            if t_diff_dof >= profile.t_sum[-1]:
                # Keep constant acceleration past this profile's own end.
                args.append(
                    (
                        t_diff_dof - profile.t_sum[-1],
                        profile.p[-1],
                        profile.v[-1],
                        profile.a[-1],
                        0.0,
                    )
                )
                continue

            # Find the correct time segment (first t_sum strictly after t_diff_dof).
            index_dof = len(profile.t_sum)
            for segment_i, t_sum_i in enumerate(profile.t_sum):
                if t_sum_i > t_diff_dof:
                    index_dof = segment_i
                    break

            if index_dof > 0:
                t_diff_dof -= profile.t_sum[index_dof - 1]

            args.append(
                (
                    t_diff_dof,
                    profile.p[index_dof],
                    profile.v[index_dof],
                    profile.a[index_dof],
                    profile.j[index_dof],
                )
            )

        return new_section, args

    def at_time(self, time: float) -> tuple[list[float], list[float], list[float]]:
        """``atTime`` (the position/velocity/acceleration convenience
        overload). ``time`` is clamped to ``[0, duration]`` (otg.md §Public
        API)."""
        clamped_time = max(0.0, min(time, self.duration))
        _new_section, integrate_args = self._state_to_integrate_from(clamped_time)

        positions: list[float] = []
        velocities: list[float] = []
        accelerations: list[float] = []
        for t, p0, v0, a0, j in integrate_args:
            p, v, a = integrate_jerk(t, p0, v0, a0, j)
            positions.append(p)
            velocities.append(v)
            accelerations.append(a)
        return positions, velocities, accelerations

    # MARK: - Position extrema

    def position_extrema(self) -> list[Bound]:
        """``getPositionExtrema`` (Trajectory-level): the min/max position
        (and the times at which they occur) reached by each DOF, merged
        across every profile section.

        Each section's own extrema are computed independently -- the times
        recorded are section-relative, not offset by the section's start
        time. This is a direct, literal port of the Swift source (see this
        chunk's Out of scope note: "Extrema across brake sections beyond
        the direct port").
        """
        dofs = self.degrees_of_freedom
        extrema = [_profile_position_extrema(self.profiles[0][dof]) for dof in range(dofs)]

        for section in self.profiles[1:]:
            for dof in range(dofs):
                section_extrema = _profile_position_extrema(section[dof])
                if section_extrema.max > extrema[dof].max:
                    extrema[dof].max = section_extrema.max
                    extrema[dof].t_max = section_extrema.t_max
                if section_extrema.min < extrema[dof].min:
                    extrema[dof].min = section_extrema.min
                    extrema[dof].t_min = section_extrema.t_min

        return extrema

    # MARK: - Internal accessors

    def _get_intermediate_durations(self) -> list[float]:
        """``get_intermediate_durations`` -- the durations at which each
        intermediate waypoint is reached."""
        return self.cumulative_times

    def _get_first_time_at_position(
        self, dof: int, position: float, time_after: float = 0.0
    ) -> float | None:
        """``get_first_time_at_position`` -- the first time this
        trajectory passes ``position`` for the given ``dof``, at or after
        ``time_after``; ``None`` if it never does (or ``dof`` is out of
        range)."""
        if dof >= self.degrees_of_freedom:
            return None

        for section_i, section in enumerate(self.profiles):
            found, time = _profile_first_state_at_position(section[dof], position, time_after)
            if found:
                section_time = self.cumulative_times[section_i - 1] if section_i > 0 else 0.0
                return section_time + time

        return None


def _profile_position_extrema(profile: Profile) -> Bound:
    """``Profile.getPositionExtrema`` -- deferred by chunk 33 to this
    module (see chunk 33's Resolution notes and this module's docstring)."""
    extrema = Bound(min=math.inf, max=-math.inf, t_min=-math.inf, t_max=-math.inf)

    if profile.brake.duration > 0.0 and profile.brake.t[0] > 0.0:
        Profile.check_step_for_position_extremum(
            0.0,
            profile.brake.t[0],
            profile.brake.p[0],
            profile.brake.v[0],
            profile.brake.a[0],
            profile.brake.j[0],
            extrema,
        )
        if profile.brake.t[1] > 0.0:
            Profile.check_step_for_position_extremum(
                profile.brake.t[0],
                profile.brake.t[1],
                profile.brake.p[1],
                profile.brake.v[1],
                profile.brake.a[1],
                profile.brake.j[1],
                extrema,
            )

    t_current_sum = 0.0
    for i in range(7):
        if i > 0:
            t_current_sum = profile.t_sum[i - 1]
        Profile.check_step_for_position_extremum(
            t_current_sum + profile.brake.duration,
            profile.t[i],
            profile.p[i],
            profile.v[i],
            profile.a[i],
            profile.j[i],
            extrema,
        )

    if profile.pf < extrema.min:
        extrema.min = profile.pf
        extrema.t_min = profile.t_sum[-1] + profile.brake.duration
    if profile.pf > extrema.max:
        extrema.max = profile.pf
        extrema.t_max = profile.t_sum[-1] + profile.brake.duration

    return extrema


def _profile_first_state_at_position(
    profile: Profile, pt: float, time_after: float = 0.0
) -> tuple[bool, float]:
    """``Profile.getFirstStateAtPosition`` -- deferred by chunk 33 to this
    module (see chunk 33's Resolution notes and this module's docstring).
    Root solving delegates to
    :func:`math_tools.functional.roots.solve_cubic` (otg.md: "the OTG
    chunks MUST NOT reimplement root solving")."""
    t_cum = 0.0
    for i in range(7):
        if profile.t[i] == 0.0:
            continue

        if abs(profile.p[i] - pt) < _ULP and t_cum >= time_after:
            return True, t_cum

        for root in solve_cubic(
            profile.j[i] / 6, profile.a[i] / 2, profile.v[i], profile.p[i] - pt
        ):
            if 0 < root and time_after - t_cum <= root <= profile.t[i]:
                return True, root + t_cum

        t_cum += profile.t[i]

    if (
        (profile.t[6] > 0.0 or profile.t_sum[-1] == 0.0)
        and abs(profile.pf - pt) < 1e-9
        and profile.t_sum[-1] >= time_after
    ):
        return True, profile.t_sum[-1]

    return False, 0.0
